#!/usr/bin/env python3
"""Library lookup (Blueprint v2.1, stage 3).  lib_tool.py check <story_plan.json> <resolve.json> ; lib_tool.py report <out.md> <plan:resolve> ...

A resolve file maps every place in a plan to a kit, and every set-dressing string and prop to something the
library can make (scene/catalogue.json):
  "piece_id" or "piece_id:LABEL" or a list of them  -> exact
  "kit"  -> part of the kit itself        "mood" -> produced by the lighting mood
  "~piece_id" -> nearest thing we have (a recorded fallback, allowed only for non-proof dressing)
  "BUILD: why" -> the library cannot make it yet
A proof item that is a fallback or BUILD blocks the plan (exit 1). Other BUILD items are listed (exit 2)."""
import json, sys, os
HERE = os.path.dirname(os.path.abspath(__file__))
CAT = json.load(open(os.path.join(HERE, "catalogue.json")))
TOKENS = {p for g in CAT["pieces"].values() for p in g} | set(CAT["aircraft_ids"]) | set(CAT["effect_ids"]) | {"briefcase", "money_bag", "kit", "mood"}


def check(plan, res):
    E, F, Bd = [], [], []          # errors, fallbacks, to build
    proofs = {b["proof"]["item"] for sc in plan["scenes"] for b in sc["beats"]}
    def one(name, val, where):
        vals = val if isinstance(val, list) else [val]
        for v in vals:
            if v is None: E.append(f"{where}: '{name}' is not resolved"); continue
            if v.startswith("BUILD"):
                (E if name in proofs else Bd).append(f"{where}: '{name}' {'is a proof item and ' if name in proofs else ''}must be built ({v[7:]})"); continue
            fb = v.startswith("~"); tok = v.lstrip("~").split(":")[0]
            if tok not in TOKENS: E.append(f"{where}: '{name}' -> '{tok}' is not in the catalogue"); continue
            if fb:
                (E if name in proofs else F).append(f"{where}: '{name}' {'is a proof item but only has a stand-in' if name in proofs else 'uses the nearest piece'}: {tok}")
    for sc in plan["scenes"]:
        pid = sc["place"]["id"]; st = res["sets"].get(pid)
        if not st: E.append(f"{sc['id']}: place '{pid}' has no kit"); continue
        kit = CAT["kits"].get(st["kit"])
        if not kit: E.append(f"{sc['id']}: kit '{st['kit']}' is not in the catalogue"); continue
        if kit["enclosed"] != (sc["place"]["kind"] == "interior"): E.append(f"{sc['id']}: place is {sc['place']['kind']} but kit '{st['kit']}' is {'enclosed' if kit['enclosed'] else 'open'}")
        for d in sc["dressing"]: one(d, res["items"].get(d), sc["id"])
    for p in plan["props"]: one(p["id"], res["props"].get(p["id"]), "prop")
    return sorted(set(E)), sorted(set(F)), sorted(set(Bd))


if __name__ == "__main__":
    if sys.argv[1] == "check":
        E, F, Bd = check(json.load(open(sys.argv[2])), json.load(open(sys.argv[3])))
        for x in E: print("ERROR", x)
        for x in Bd: print("BUILD", x)
        for x in F: print("FALLBACK", x)
        print(f"{os.path.basename(sys.argv[2])}: {len(E)} errors, {len(Bd)} to build, {len(F)} fallbacks")
        sys.exit(1 if E else (2 if Bd else 0))
    else:
        out = sys.argv[2]; L = ["# Library coverage of the three story plans", "", "Generated by `scene/lib_tool.py report`. Every place, set piece and prop in each plan is looked up in",
                                 "`scene/catalogue.json`. Character actions are a separate question (see the end).", ""]
        tot = [0, 0, 0, 0]
        for pair in sys.argv[3:]:
            pp, rp = pair.split(":"); plan = json.load(open(pp)); res = json.load(open(rp)); E, F, Bd = check(plan, res)
            n = len({d for sc in plan["scenes"] for d in sc["dressing"]}) + len(plan["props"])
            tot[0] += n; tot[1] += len(E); tot[2] += len(Bd); tot[3] += len(F)
            L += [f"## {plan['title']}", "", f"{len(plan['scenes'])} scenes, {n} distinct set pieces and props: {n - len(E) - len(Bd) - len(F)} made exactly, {len(F)} by a stand-in, {len(Bd) + len(E)} not yet possible.", ""]
            L += [f"- **Blocks the plan:** {x}" for x in E] + [f"- To build: {x}" for x in Bd] + [f"- Stand-in: {x}" for x in F] + [""]
        L.insert(4, f"**Total: {tot[0]} items; {tot[0] - tot[1] - tot[2] - tot[3]} made exactly, {tot[3]} by a stand-in, {tot[1] + tot[2]} not yet possible ({tot[1]} of those block a plan).**\n")
        can = CAT["character"]["cannot_yet"]
        L += ["## Character actions still missing", "", "The character can stand, walk, sit, kneel and crouch, and pose each arm. It cannot yet: " + "; ".join(can) + ".", ""]
        open(out, "w").write("\n".join(L) + "\n"); print(L[4])
