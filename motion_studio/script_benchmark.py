"""Prompt and JSON scoring helpers for the Stickman Motion Studio model benchmark."""
import json

BRIEF = {
    "topic": "What would happen if the Sun suddenly disappeared?",
    "format": "YouTube Short, 30–60 seconds, vertical 9:16",
    "audience": "general viewers",
    "mascot": "Large round white head, thick dark outline, two small black oval eyes, expressive eyebrows, small mouth, thin black stick arms and legs, simple body, no gloves or shoes. Flat 2D cartoon, clean thick outlines, soft muted colours.",
    "requirements": [
        "Write a strong hook and satisfying ending.",
        "Narration should sound natural aloud and target 90–125 words.",
        "Create 10–14 useful scenes; avoid filler.",
        "Keep character identity, costume, locations and recurring props consistent.",
        "Each scene needs narration_segment, action, expression, camera, composition, environment, lighting, continuity_from_previous and a detailed independently usable image_prompt.",
        "No text, captions, labels, speech bubbles or watermarks inside generated images.",
        "List factual claims requiring source verification; do not pretend they are verified.",
        "Return JSON only, without markdown fences."
    ]
}

SCHEMA = {
    "title": "string", "hook": "string", "estimated_duration_seconds": "integer",
    "narration": "string",
    "claims_to_verify": [{"claim": "string", "why_check": "string"}],
    "cast_bible": [{"character_id": "string", "appearance": "string", "costume": "string"}],
    "continuity_bible": {"global_style": "string", "locations": ["string"], "recurring_props": ["string"], "rules": ["string"]},
    "scenes": [{
        "scene_number": "integer", "duration_seconds": "number", "narration_segment": "string",
        "action": "string", "expression": "string", "camera": "string", "composition": "string",
        "environment": "string", "lighting": "string", "continuity_from_previous": "string",
        "image_prompt": "string"
    }],
    "final_continuity_checklist": ["string"]
}

def build_prompt():
    return (
        "You are the scriptwriter and visual director for Stickman Thoughts. Create a production-ready Short plan.\n"
        + json.dumps(BRIEF, ensure_ascii=False, indent=2)
        + "\nRequired JSON shape:\n" + json.dumps(SCHEMA, ensure_ascii=False, indent=2)
        + "\nReturn only valid JSON. Detailed image prompts must be generated by you, not the user."
    )

def score_output(text):
    try:
        data = json.loads(text.strip())
    except Exception as exc:
        return {"score": 0, "json_valid": False, "error": str(exc)}
    scenes = data.get("scenes", [])
    fields = ["scene_number", "narration_segment", "action", "expression", "camera",
              "composition", "environment", "lighting", "continuity_from_previous", "image_prompt"]
    checks = {
        "hook": bool(data.get("hook")),
        "narration": bool(data.get("narration")),
        "scene_count_10_14": 10 <= len(scenes) <= 14,
        "scene_fields_complete": bool(scenes) and all(all(str(s.get(k, "")).strip() for k in fields) for s in scenes),
        "claims_to_verify": isinstance(data.get("claims_to_verify"), list),
        "cast_bible": bool(data.get("cast_bible")),
        "continuity_bible": isinstance(data.get("continuity_bible"), dict),
        "final_checklist": isinstance(data.get("final_continuity_checklist"), list)
    }
    return {"score": round(100 * sum(checks.values()) / len(checks)), "json_valid": True, "checks": checks}
